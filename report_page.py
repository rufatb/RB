    p.add_argument('--report', required=True, help='frozen report.json from daily_job')
    p.add_argument('--output', required=True, help='HTML file to write')
    a = p.parse_args(argv)
    with open(a.report) as handle:
        digest = json.load(handle)
    with open(a.output, 'w') as handle:
        handle.write(render(digest))
    print(a.output)
    return 0


