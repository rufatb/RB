"""Standalone HTML page view of the frozen computation.

A THIRD RENDERER, not a third source of truth. Like `daily_render` and
`email_render` it consumes `brief.compute`'s frozen schema-v2 output and never
fetches, selects, scores, allocates or persists. It exists because the daily
page was being rewritten by hand each morning, and a page regenerated by hand
drifts: the day this renderer was written, the standing instruction for that
rewrite had to repeat "render no share count on an ABSTAIN leg" in capitals
because there was nothing to enforce it. Here it is enforced by construction —
`_alloc_cell` cannot emit a size for an abstained leg, and a test fails if it
ever does.

Pure: give it a digest, get a string. No clock read, no network, no writes.
"""
